    [Test]
    public async ValueTask NestedMultiple() {
        const string input = """
            using InlineCompositionAttributes;

            namespace MyCode;

            public sealed class Test {
                public int myField = 5;
            }

            public sealed partial class A {
                public partial record struct B {
                    public partial struct C {
